// Сұрақ жасау: себеп берілсе — салдарды, кейде керісінше. Қате нұсқалар сол сыныптың басқа жұптарынан.
export function causeQuestions(grade, count, rnd = Math.random) {
  const shuffle = a => { a = a.slice(); for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
  const pool = CAUSES.filter(c => c.grade === grade);
  if (pool.length < 4) return [];
  return shuffle(pool).slice(0, count).map(p => {
    const reverse = rnd() < 0.35;
    const others = shuffle(pool.filter(x => x !== p)).slice(0, 3).map(x => reverse ? x.cause : x.effect);
    const right = reverse ? p.cause : p.effect;
    const o = shuffle([right, ...others]);
    return {
      kind: "cause",
      q: reverse ? "Мына салдарға не себеп болды?\n«" + p.effect + "»" : "Мына оқиғаның салдары қандай болды?\n«" + p.cause + "»",
      o, a: o.indexOf(right)
    };
  });
}
